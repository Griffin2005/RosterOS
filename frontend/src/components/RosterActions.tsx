import { useEffect, useState } from "react";
import { Download, GitCompare, Send, Sparkles, Wand2 } from "lucide-react";
import { api, canManage, download, waitJob, type RosterMeta } from "../api";
import { useApp } from "../ctx";
import { Modal } from "./Modal";

export function RosterActions({ compact = false }: { compact?: boolean }) {
  const { user, grid, month, reload, toast, setRosterId, rosterId } = useApp();
  const [busy, setBusy] = useState<string | null>(null);
  const [versions, setVersions] = useState<RosterMeta[]>([]);
  const [diff, setDiff] = useState<any | null>(null);
  const manage = canManage(user);
  const r = grid?.roster;
  const openHard = grid ? grid.conflicts.filter((c) => c.severity === "HARD" && !c.acknowledged).length : 0;

  useEffect(() => {
    if (manage || user?.role === "AUDITOR") api(`/api/rosters?month=${month}`).then(setVersions).catch(() => {});
  }, [month, grid?.roster.id, manage, user?.role]);

  const run = async (label: string, fn: () => Promise<void>) => {
    setBusy(label);
    try { await fn(); } catch (e: any) { toast(e.message, true); } finally { setBusy(null); }
  };

  const generate = () => run("generate", async () => {
    const { job_id } = await api("/api/rosters/generate", { body: { month } });
    const j = await waitJob(job_id);
    if (j.status !== "DONE") throw new Error(j.error || "Generation failed");
    setRosterId(null);
    await reload();
    toast("New draft generated by the solver.");
  });
  const repair = () => run("repair", async () => {
    const { job_id } = await api(`/api/rosters/${r!.id}/repair`, { body: {} });
    const j = await waitJob(job_id);
    if (j.status !== "DONE") throw new Error(j.error || "Repair failed");
    setRosterId(null);
    await reload();
    toast("Repair draft ready. Review the changes, then publish.");
  });
  const publish = () => run("publish", async () => {
    const out = await api(`/api/rosters/${r!.id}/publish`, { body: {} });
    setRosterId(null);
    await reload();
    toast(`Published v${out.roster.version}. ${out.notified} people notified${out.sheets.ok ? ", Google Sheet updated" : ""}.`);
  });
  const showDiff = () => run("diff", async () => setDiff(await api(`/api/rosters/${r!.id}/diff`)));

  return (
    <div className="actions">
      {versions.length > 0 && (
        <select className="input" aria-label="Roster version" value={rosterId || r?.id || ""}
                onChange={(e) => setRosterId(e.target.value === versions[0]?.id ? null : e.target.value)}>
          {versions.map((v) => <option key={v.id} value={v.id}>v{v.version} · {v.status.toLowerCase()} · {v.kind.toLowerCase()}</option>)}
        </select>
      )}
      {r && <span className={`tag ${r.status === "PUBLISHED" ? "ok" : r.status === "DRAFT" ? "soft" : "neutral"}`}>{r.status}</span>}
      {manage && (
        <button className="btn" onClick={generate} disabled={!!busy}>
          {busy === "generate" ? <span className="spinner" /> : <Sparkles size={16} />}{r ? "Regenerate" : "Generate roster"}
        </button>
      )}
      {manage && r && openHard > 0 && (
        <button className="btn" onClick={repair} disabled={!!busy}>
          {busy === "repair" ? <span className="spinner" /> : <Wand2 size={16} />}Auto-repair
        </button>
      )}
      {r?.parent_id && !compact && <button className="btn ghost" onClick={showDiff} disabled={!!busy}><GitCompare size={16} />Changes</button>}
      {r && !compact && (
        <button className="btn ghost" onClick={() => download(`/api/rosters/${r.id}/export.xlsx`, `roster-${month}-v${r.version}.xlsx`).catch((e) => toast(e.message, true))}>
          <Download size={16} />Excel
        </button>
      )}
      {r && !compact && (
        <button className="btn ghost" onClick={() => download(`/api/rosters/${r.id}/export.csv`, `roster-${month}-v${r.version}.csv`).catch((e) => toast(e.message, true))}>
          <Download size={16} />CSV
        </button>
      )}
      {manage && r?.status === "DRAFT" && (
        <button className="btn primary" onClick={publish} disabled={!!busy || openHard > 0} title={openHard ? "Resolve or acknowledge hard conflicts first" : ""}>
          {busy === "publish" ? <span className="spinner" /> : <Send size={16} />}Publish
        </button>
      )}
      {diff && (
        <Modal title={`Changes in v${r?.version} vs v${diff.against?.version}`} onClose={() => setDiff(null)}>
          {diff.changes.length === 0 && <p className="muted">No cell changed.</p>}
          <div className="table-wrap">
            <table className="data">
              <thead><tr><th>Date</th><th>Employee</th><th>Before</th><th>After</th></tr></thead>
              <tbody>
                {diff.changes.map((c: any, i: number) => (
                  <tr key={i}>
                    <td className="num">{c.date}</td><td>{c.employee}</td>
                    <td>{c.before ? `${c.before.status}${c.before.lines?.length ? ` · ${c.before.lines.join(", ")}` : ""}` : "—"}</td>
                    <td><b>{c.after.status}</b>{c.after.lines?.length ? ` · ${c.after.lines.join(", ")}` : ""}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </Modal>
      )}
    </div>
  );
}
