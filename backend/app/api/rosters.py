def _month(text: str) -> date:
    try:
        y, m = text.split("-")[:2]
        return date(int(y), int(m), 1)
    except ValueError:
        raise HTTPException(422, "Month must look like 2026-12")


def _roster(db: Session, rid: str) -> M.Roster:
    r = db.get(M.Roster, rid)
    if r is None:
        raise HTTPException(404, "Roster not found")
    return r


def _guard(fn, *a, **kw):
    try:
        return fn(*a, **kw)
    except R.RosterError as e:
        raise HTTPException(409, str(e))


