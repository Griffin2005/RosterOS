@router.get("/rosters/current")
def current_roster(month: str, db: Session = Depends(get_db), user: User = Depends(current_user)):
    m = _month(month)
    r = R.latest(db, m) if user.role in WRITE_ROSTER | {"AUDITOR"} else R.published(db, m)
