class EditsIn(BaseModel):
    edits: list[dict]


@router.post("/rosters/{rid}/edits")
def edit_cells(rid: str, body: EditsIn, db: Session = Depends(get_db), user: User = Depends(require(WRITE_ROSTER))):
    if user.role == "POD_LEAD":
        pod_emps = {e.id for e in db.scalars(select(M.Employee).where(M.Employee.pod_id == user.scope_id))}
        if any(e["employee_id"] not in pod_emps for e in body.edits):
            raise HTTPException(403, "Pod leads can only edit schedules in their own pod.")
    r, result = _guard(R.apply_edits, db, rid, body.edits, user.username)
    return {"roster": R.roster_meta(r), **result}


