@router.get("/sheets/{which}")
def view_sheet(which: str, _: User = Depends(current_user)):
    """Read a workbook so the UI can show the 'Google Sheet' side by side."""
    from ..integrations.google import google
    s = get_settings()
    sid = s.rules_spreadsheet_id if which == "rules" else s.dashboard_spreadsheet_id
    if s.sheets_mode == "embedded":
        from ..integrations import google_mock
        return google_mock.spreadsheet_view(sid)
    if "googleapis.com" not in s.sheets_base_url:
        import httpx
        r = httpx.get(f"{s.sheets_base_url.rstrip('/')}/mock/spreadsheets/{sid}", timeout=15)
        r.raise_for_status()
        return r.json()
    g = google()
    tabs = ["ServiceLines", "CoverageOverrides"] if which == "rules" else ["Company", "Coverage", "Open conflicts"]
    return {"id": sid, "revision": g.file_version(sid), "tabs": {t: g.get_values(sid, f"{t}!A1:AZ500") for t in tabs}}


