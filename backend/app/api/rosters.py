@router.put("/sheets/rules/{tab}")
def edit_rules_sheet(tab: str, body: SheetTabIn, user: User = Depends(require(MANAGE))):
    """Simulates the ops team editing the Google Sheet (mock only; with real
    Google, people edit the Sheet itself)."""
    s = get_settings()
    if s.sheets_mode == "embedded":
        from ..integrations import google_mock
        google_mock.batch_update(s.rules_spreadsheet_id, [{"range": f"{tab}!A1", "values": body.rows}])
        return google_mock.spreadsheet_view(s.rules_spreadsheet_id)
    if "googleapis.com" in s.sheets_base_url:
        raise HTTPException(409, "Edit the real Google Sheet directly.")
    import httpx
    r = httpx.put(f"{s.sheets_base_url.rstrip('/')}/mock/spreadsheets/{s.rules_spreadsheet_id}/tabs/{tab}",
                  json=body.rows, timeout=15)
    r.raise_for_status()
    return r.json()


